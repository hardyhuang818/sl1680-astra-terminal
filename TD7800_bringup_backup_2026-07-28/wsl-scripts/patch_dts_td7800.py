# 匹配 &drm 块里的整个 dsi_panel { ... command = ...>; \n\t}; 节点
pat = re.compile(r"\tdsi_panel \{.*?command = /bits/ 8 <.*?>;\n\t\};\n", re.S)
m = pat.search(src)
if not m:
    sys.exit("FATAL: dsi_panel node pattern not found")
if src.count("\tdsi_panel {") != 1:
    sys.exit("FATAL: multiple dsi_panel nodes?")

shutil.copyfile(DTS, BAK)
out = src[:m.start()] + NEW_NODE + src[m.end():]
open(DTS, "w", encoding="utf-8").write(out)
print(f"OK: replaced {m.end()-m.start()} chars with {len(NEW_NODE)} chars")
print(f"backup: {BAK}")
# 快速自检
chk = open(DTS, encoding="utf-8").read()
for k in ("ACTIVE_WIDTH = <1280>", "Byte_clk = <48975>", "0x9C 0x04 0x31", "rpi_panel_regulator@45"):
    print(("✓" if k in chk else "✗"), k)
print("power-supply still in dsi_panel?:", "power-supply" in chk[chk.find("dsi_panel"):chk.find("hdmi_tx")])
